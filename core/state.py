from typing import TypedDict


class SalesState(TypedDict, total=False):

    # ========================================================
    # USER / AUTH
    # ========================================================

    user_request: str
    user_email: str

    # ========================================================
    # SEARCH
    # ========================================================

    business_type: str
    search_query: str
    location: str

    # ========================================================
    # LEADS
    # ========================================================
    lead_limit: int
    leads: list
    qualified_leads: list
    researched_leads: list

    # ========================================================
    # EMAIL
    # ========================================================

    emails: list

    # ========================================================
    # HUMAN APPROVAL
    # ========================================================

    approval_status: str

    # ========================================================
    # EXCEL
    # ========================================================

    excel_file: str

    # ========================================================
    # WORKFLOW
    # ========================================================
    workflow_plan: list[str]
    current_stage: str
    retry_counts: dict
    status: str
    error: str